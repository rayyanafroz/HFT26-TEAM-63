"""Writes engine/core/src/patterns.rs: every detector pattern and constant, copied from the Python reference.

The Rust engine compiles these strings through `pyre::translate`, so a rule changed in Python reaches Rust by
regenerating, never by hand:

    .venv/bin/python engine/tools/gen_patterns.py

tests/test_engine_tables.py fails if the committed file is out of date. Patterns the Rust side runs in
another form (zero-width lookaheads it walks by hand) are checked here against the exact Python text, so a
change to them stops the build until the Rust side is updated too.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from shadowlens.analysis import code, encoded, masking, pii, secrets  # noqa: E402
from shadowlens.analysis.catalog import RULES  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "core" / "src" / "patterns.rs"

# Run by hand-written code in Rust instead of a regex (the regex form is slow or zero-width there). If one
# of these changes in Python, update the Rust code named here, then this table.
HAND_WRITTEN = {
    (pii, "_AADHAAR_RE"): (r"(?<!\d)(?=([2-9]\d{3}[\s\-.]?\d{4}[\s\-.]?\d{4})(?!\d))", "pii.rs: Pii::aadhaar"),
    (pii, "_IBAN_START_RE"): (r"(?i)\b(?=[A-Z]{2}\d{2})", "pii.rs: Pii::ibans"),
    (pii, "_IBAN_RUN_RE"): (r"(?i)[A-Z]{2}\d{2}(?: ?[A-Z0-9]{1,4}){3,9}\b", "pii.rs: iban_run_at"),
    (pii, "_UUID_PREFIX_RE"): (r"[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-", "pii.rs: ends_a_uuid"),
    (encoded, "_B64"): (r"(?<![A-Za-z0-9+/_\-=])[A-Za-z0-9+/_\-]{24,4096}={0,2}(?![A-Za-z0-9+/_\-])", "encoded.rs: base64_tokens"),
    (encoded, "_HEX"): (r"(?<![0-9A-Fa-f])(?:[0-9A-Fa-f]{2}){12,2048}(?![0-9A-Fa-f])", "encoded.rs: hex_tokens"),
}


def lit(value: str) -> str:
    for hashes in range(1, 6):
        fence = "#" * hashes
        if f'"{fence}' not in value:
            return f'r{fence}"{value}"{fence}'
    raise ValueError(f"cannot quote {value!r}")


def flags(pattern: re.Pattern[str]) -> str:
    inline = pattern.pattern.startswith("(?i)")
    if pattern.flags & re.IGNORECASE and not inline:
        raise ValueError(f"IGNORECASE without an inline (?i): {pattern.pattern!r}")
    if pattern.flags & re.VERBOSE or pattern.flags & re.ASCII:
        raise ValueError(f"unsupported flags: {pattern.pattern!r}")
    return ("Flags { multiline: %s, dotall: %s }"
            % (str(bool(pattern.flags & re.MULTILINE)).lower(), str(bool(pattern.flags & re.DOTALL)).lower()))


def pat(name: str, pattern: re.Pattern[str]) -> str:
    return f"pub const {name}: (&str, Flags) = ({lit(pattern.pattern)}, {flags(pattern)});\n"


def strs(name: str, values) -> str:
    return f"pub const {name}: &[&str] = &[{', '.join(lit(v) for v in values)}];\n"


def nums(name: str, kind: str, values) -> str:
    return f"pub const {name}: &[{kind}] = &[{', '.join(str(v) for v in values)}];\n"


def main() -> None:
    for (module, name), (expected, where) in HAND_WRITTEN.items():
        actual = getattr(module, name).pattern
        if actual != expected:
            raise SystemExit(f"{module.__name__}.{name} changed; update engine/core/src/{where}, then HAND_WRITTEN here:\n  {actual}")
    out = [
        "// Generated by engine/tools/gen_patterns.py from src/shadowlens/analysis. Do not edit.\n",
        "#![allow(dead_code)]\n\nuse crate::pyre::Flags;\n\n",
        "// ---- secrets.py\n",
        "pub const NAMED_PATTERNS: &[(&str, (&str, Flags))] = &[\n",
        *(f"    ({lit(rule)}, ({lit(p.pattern)}, {flags(p)})),\n" for rule, p in secrets.NAMED_PATTERNS.items()),
        "];\n",
        "pub const VENDOR_PATTERNS: &[(&str, Flags)] = &[\n",
        *(f"    ({lit(p.pattern)}, {flags(p)}),\n" for p in secrets.VENDOR_PATTERNS),
        "];\n",
    ]
    for name in ("AWS_SECRET_RE", "JWT_RE", "_NAMED_PREFILTER_RE", "GENERIC_RE", "GENERIC_PLAIN_RE", "GENERIC_QUOTED_RE",
                 "PAIR_RE", "BEARER_RE", "CLI_PASSWORD_RE", "URL_CREDENTIALS_RE", "GENERIC_CAMEL_RE", "_REFERENCE_RE",
                 "_UUID_RE", "_HEX_RE", "_MODEL_FIELD_BEFORE_RE", "_INTEGRITY_HASH_RE", "_WORD_PART_RE", "_SEPARATORS_RE"):
        out.append(pat(name.lstrip("_"), getattr(secrets, name)))
    out.append(strs("NOT_A_VALUE_PREFIXES", secrets._NOT_A_VALUE_PREFIXES))
    out.append(f"pub const ENTROPY_TOKEN: &str = {lit(secrets._entropy_token_re(24).pattern.replace('{24,}', '{{{min},}}'))};\n")

    out.append("\n// ---- pii.py\n")
    for name in ("_DIGIT_RUN_RE", "_SINGLE_DIGITS_RE", "_DIGIT_GROUP_RE", "_IBAN_GROUP_RE", "_SSN_RE",
                 "_SSN_WORDED_RE", "_PAN_RE", "_EMAIL_RE", "_EMAIL_SPELLED_RE", "_HOSTNAME_RE", "_PRIVATE_IP_RE"):
        out.append(pat(name.lstrip("_"), getattr(pii, name)))
    out.append("pub const PHONE_PATTERNS: &[(&str, Flags)] = &[\n"
               + "".join(f"    ({lit(p.pattern)}, {flags(p)}),\n" for p in pii._PHONE_PATTERNS) + "];\n")
    out.append(nums("CARD_LENGTHS", "usize", pii._CARD_LENGTHS))
    out.append(f"pub const CARD_MIN_DIGITS: usize = {pii._CARD_MIN_DIGITS};\npub const CARD_MAX_DIGITS: usize = {pii._CARD_MAX_DIGITS};\n")
    out.append(f"pub const CARD_FIRST_DIGITS: &str = {lit(pii._CARD_FIRST_DIGITS)};\n")
    out.append(f"pub const CARD_MAX_GROUPS: usize = {pii._CARD_MAX_GROUPS};\npub const CARD_MIN_GROUP_DIGITS: usize = {pii._CARD_MIN_GROUP_DIGITS};\n")
    out.append(f"pub const PAN_FOURTH_LETTERS: &str = {lit(''.join(sorted(pii._PAN_FOURTH_LETTERS)))};\n")
    out.append(strs("HOST_SUFFIXES", pii._HOST_SUFFIXES))
    out.append(strs("GROUPED_RULES", sorted(pii.GROUPED_RULES)))

    out.append("\n// ---- encoded.py\n")
    for name in ("_KEY_START", "_NEXT_PIECE"):
        out.append(pat(name.lstrip("_"), getattr(encoded, name)))
    for name in ("MAX_TOKENS", "MAX_TOKEN_CHARS", "MIN_DECODED_CHARS", "MAX_PIECES"):
        out.append(f"pub const {name}: usize = {getattr(encoded, name)};\n")
    out.append(f"pub const PRINTABLE_RATIO: f64 = {encoded.PRINTABLE_RATIO!r};\n")
    out.append(f"pub const MIN_PIECE_ENTROPY: f64 = {encoded.MIN_PIECE_ENTROPY!r};\n")

    out.append("\n// ---- code.py\n")
    for name in ("_MARKER_RE", "_COPYRIGHT_RE", "_FENCE_RE", "_CODE_TOKEN_RE", "_CODE_LINE_RE"):
        out.append(pat(name.lstrip("_"), getattr(code, name)))

    out.append("\n// ---- catalog.py: (rule id, severity, confidence, overlap priority; lower wins)\n")
    out.append("pub const RULES: &[(&str, &str, f64, u32)] = &[\n"
               + "".join(f"    ({lit(rid)}, {lit(r.severity)}, {r.confidence!r}, {r.priority}),\n" for rid, r in RULES.items())
               + "];\n")

    out.append("\n// ---- masking.py\n")
    out.append(pat("PLACEHOLDER_RE", masking.PLACEHOLDER_RE))
    OUT.write_text("".join(out), encoding="utf-8")
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
