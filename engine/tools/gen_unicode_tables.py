"""Writes engine/core/src/tables.rs from Python's own Unicode database.

The Rust engine must agree with the Python reference character for character. Rust's Unicode tables can
be a different Unicode version, and some Python predicates (str.isdigit, str.isprintable, the regex
classes \\w, \\d and \\s) have no exact Rust equivalent, so every table the engine needs is generated here
from the Python that runs the reference:

    .venv/bin/python engine/tools/gen_unicode_tables.py

tests/test_engine_tables.py fails if the committed file is out of date.
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / "src"))

from shadowlens.analysis.normalize import _INTERESTING, _clean_char  # noqa: E402

OUT = Path(__file__).resolve().parents[1] / "core" / "src" / "tables.rs"
MAX = 0x110000


def ranges(predicate) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    start = None
    for cp in range(MAX):
        hit = predicate(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def rust_ranges(name: str, doc: str, items: list[tuple[int, int]]) -> str:
    body = "".join(f"    (0x{a:X}, 0x{b:X}),\n" for a, b in items)
    return f"/// {doc}\npub static {name}: &[(u32, u32)] = &[\n{body}];\n\n"


def rust_str(value: str) -> str:
    return '"' + "".join(f"\\u{{{ord(c):X}}}" for c in value) + '"'


def digit_runs() -> list[tuple[int, int, int]]:
    """Nd characters as (first, last, value of first): Unicode keeps each set of ten digits together."""
    runs: list[tuple[int, int, int]] = []
    for cp in range(MAX):
        ch = chr(cp)
        if unicodedata.category(ch) != "Nd":
            continue
        value = unicodedata.decimal(ch)
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] + (cp - runs[-1][0]) == value:
            runs[-1] = (runs[-1][0], cp, runs[-1][2])
        else:
            runs.append((cp, cp, value))
    return runs


def main() -> None:
    space = [cp for cp in range(MAX) if re.match(r"\s", chr(cp))]
    clean_drop: list[int] = []
    clean_map: list[tuple[int, str]] = []
    for cp in range(MAX):
        ch = chr(cp)
        if not _INTERESTING.fullmatch(ch):
            continue
        cleaned = _clean_char(ch)
        if cleaned == ch:
            continue
        if cleaned == "":
            clean_drop.append(cp)
        else:
            clean_map.append((cp, cleaned))
    drop_ranges: list[tuple[int, int]] = []
    for cp in clean_drop:
        if drop_ranges and drop_ranges[-1][1] == cp - 1:
            drop_ranges[-1] = (drop_ranges[-1][0], cp)
        else:
            drop_ranges.append((cp, cp))

    parts = [
        "// Generated by engine/tools/gen_unicode_tables.py from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.\n\n",
        f'pub const UNICODE_VERSION: &str = "{unicodedata.unidata_version}";\n\n',
        rust_ranges("WORD", "Python regex \\w: str.isalnum() or \"_\".", ranges(lambda c: c.isalnum() or c == "_")),
        rust_ranges("DIGIT_ND", "Python regex \\d: category Nd.", ranges(lambda c: unicodedata.category(c) == "Nd")),
        rust_ranges("ALPHA", "str.isalpha() for one character.", ranges(str.isalpha)),
        rust_ranges("ISDIGIT", "str.isdigit() for one character.", ranges(str.isdigit)),
        rust_ranges("UPPER", "str.isupper() for one character.", ranges(str.isupper)),
        rust_ranges("PRINTABLE", "str.isprintable() for one character.", ranges(str.isprintable)),
        rust_ranges("LETTER_NOT_DIGIT", "Python [^\\W\\d_]: \\w without digits and \"_\".",
                    ranges(lambda c: c.isalnum() and unicodedata.category(c) != "Nd")),
        "/// Python regex \\s.\npub static SPACE: &[u32] = &[" + ", ".join(f"0x{cp:X}" for cp in space) + "];\n\n",
        "/// Nd digit runs: (first, last, decimal value of first).\npub static DIGIT_RUNS: &[(u32, u32, u32)] = &[\n"
        + "".join(f"    (0x{a:X}, 0x{b:X}, {v}),\n" for a, b, v in digit_runs()) + "];\n\n",
        rust_ranges("CLEAN_DROP", "Characters normalize.fold drops (invisible, joiners, combining, control).", drop_ranges),
        "/// Characters normalize.fold rewrites (NFKC, plain dashes, look-alike letters), sorted.\n"
        "pub static CLEAN_MAP: &[(u32, &str)] = &[\n"
        + "".join(f"    (0x{cp:X}, {rust_str(v)}),\n" for cp, v in clean_map) + "];\n",
    ]
    OUT.write_text("".join(parts), encoding="utf-8")
    print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB, {len(clean_map)} mapped, {len(drop_ranges)} drop ranges)")


if __name__ == "__main__":
    main()
